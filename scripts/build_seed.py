"""Build the starting data from Kurt's lists.

Usage:
    python3 scripts/build_seed.py LIST_DOC.xlsx RAB_material_data_sheets.xlsx

Writes:
    supabase/seed.sql      reference lists + office-only prices for Supabase
    supabase/staff.csv     staff names and groups; fill in mobiles, then run
                           scripts/create-staff.mjs
    src/demo-seed.json     the same data for the click-through preview
"""
import csv
import json
import pathlib
import sys

import openpyxl

ROOT = pathlib.Path(__file__).resolve().parent.parent
lists_path, register_path = sys.argv[1], sys.argv[2]

ws = openpyxl.load_workbook(lists_path, data_only=True)["Lists"]
cust_ws = openpyxl.load_workbook(lists_path, data_only=True)["Customers"]
reg_ws = openpyxl.load_workbook(register_path)["Material data sheets"]

rows = list(ws.iter_rows(values_only=True))
head = next(i for i, r in enumerate(rows) if r[1] == "Yard Location")
price_head = next(i for i, r in enumerate(rows) if r[3] == "COST")
top = rows[head + 1:price_head]

# Yard locations: column B under 'Yard Location'.
locations = [r[1].strip() for r in top if r[1]]

# Staff: columns C-F (Office, Yard, Painters, Blasters). Kurt: Dave and Woody also do QA.
group_cols = {2: "office", 3: "yard", 4: "painter", 5: "blaster"}
staff = {}
for r in top:
    for col, group in group_cols.items():
        if r[col]:
            staff.setdefault(r[col].strip(), []).append(group)
for name in ("Dave", "Woody"):
    staff[name].append("qa")

# Materials: rows after the COST/PRICE header; column A marks PRIMERS / PAINT.
materials, kind = [], None
for r in rows[price_head + 1:]:
    if r[0]:
        kind = {"PRIMERS": "primer", "PAINT": "topcoat"}[r[0].strip()]
    if r[1] and r[1] != "PRIMER" and r[3] is not None:
        materials.append({"name": r[1].strip(), "type": kind,
                          "cost_per_l": round(r[3], 2), "charge_per_l": round(r[4], 2)})

# Data sheet links from the register.
register = {}
for r in reg_ws.iter_rows(min_row=2):
    register[r[1].value.strip()] = {
        "manufacturer": r[4].value,
        "sds_status": r[5].value,
        "sds_url": r[6].hyperlink.target if r[6].hyperlink else None,
        "pds_url": r[7].hyperlink.target if r[7].hyperlink else None,
        "notes": r[8].value,
    }
for m in materials:
    m.update(register.get(m["name"], {}))

# Rates: columns G (name), I (cost), J (price). Kurt: labour rates are per hour,
# Transport / NDT / Sticker kit / Consumables are flat charges.
STAGE_OF = {"WASH": "Wash Bay", "BLAST MASK": "Blast Room", "BLAST": "Blast Room",
            "BLASTERS (2)": "Blast Room", "HANDLING": "Handling", "PREP WORK": "Prep",
            "PRIME": "Prime", "PAINT": "Paint", "DEMASKING & QA": "QA"}
DEFAULT_RATE = {"WASH", "BLAST", "HANDLING", "PREP WORK", "PRIME", "PAINT", "DEMASKING & QA"}
labour_rates, extras = [], []
for r in rows[price_head + 1:]:
    if r[6] and r[8] is not None:
        name = r[6].strip()
        pretty = name.title().replace("Ndt", "NDT").replace("Qa", "QA")
        if name in STAGE_OF:
            labour_rates.append({"name": pretty, "stage": STAGE_OF[name],
                                 "cost_per_hour": round(r[8], 2), "charge_per_hour": round(r[9], 2),
                                 "is_default": name in DEFAULT_RATE})
        else:
            extras.append({"name": pretty, "unit_cost": round(r[8], 2), "unit_charge": round(r[9], 2)})

customers = sorted({r[0].strip() for r in cust_ws.iter_rows(min_row=3, values_only=True) if r[0]},
                   key=str.casefold)
stages = ["Wash Bay", "Blast Room", "Handling", "Prep", "Prime", "Paint", "QA"]


def q(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


sql = ["-- Generated by scripts/build_seed.py from Kurt's lists. Safe to run once on a new database.", "begin;"]
sql += [f"insert into stages (name, sort_order) values ({q(s)}, {i + 1});" for i, s in enumerate(stages)]
sql += [f"insert into yard_locations (name, sort_order) values ({q(n)}, {i + 1});" for i, n in enumerate(locations)]
sql += [f"insert into customers (name) values ({q(c)});" for c in customers]
for m in materials:
    sql.append(
        "insert into materials (name, type, manufacturer, sds_url, pds_url, sds_status, notes) values "
        f"({q(m['name'])}, {q(m['type'])}, {q(m.get('manufacturer'))}, {q(m.get('sds_url'))}, "
        f"{q(m.get('pds_url'))}, {q(m.get('sds_status'))}, {q(m.get('notes'))});")
    sql.append(
        "insert into material_prices (material_id, cost_per_l, charge_per_l) "
        f"select id, {m['cost_per_l']}, {m['charge_per_l']} from materials where name = {q(m['name'])};")
for r in labour_rates:
    sql.append(
        "insert into labour_rates (name, stage_id, cost_per_hour, charge_per_hour, is_default) "
        f"select {q(r['name'])}, id, {r['cost_per_hour']}, {r['charge_per_hour']}, {q(r['is_default'])} "
        f"from stages where name = {q(r['stage'])};")
sql += [f"insert into extras (name, unit_cost, unit_charge) values ({q(e['name'])}, {e['unit_cost']}, {e['unit_charge']});"
        for e in extras]
sql.append("commit;")
(ROOT / "supabase/seed.sql").write_text("\n".join(sql) + "\n")

staff_csv = ROOT / "supabase/staff.csv"
known = {}
if staff_csv.exists():  # keep mobiles already filled in
    known = {r["name"]: r["mobile"] for r in csv.DictReader(staff_csv.open())}
with open(staff_csv, "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["name", "groups", "mobile"])
    for name, groups in staff.items():
        w.writerow([name, " ".join(groups), known.get(name, "")])

demo = {"stages": stages, "locations": locations, "customers": customers, "materials": materials,
        "labour_rates": labour_rates, "extras": extras,
        "staff": [{"name": n, "groups": g} for n, g in staff.items()]}
(ROOT / "src/demo-seed.json").write_text(json.dumps(demo, indent=1))

print(f"{len(stages)} stages, {len(locations)} locations, {len(customers)} customers, "
      f"{len(materials)} materials, {len(labour_rates)} labour rates, {len(extras)} extras, {len(staff)} staff")
